#!/usr/bin/env node
/**
 * sync-favorite-films.mjs — MUBI "Favorite films" list → app/data/favoriteFilms.ts
 *
 * Fetches the ranked list from the public MUBI API and regenerates the static
 * data file the Favorites tab on /list-of-seen-films renders from. Re-run it
 * whenever the list is re-ordered on MUBI.
 *
 * Usage:
 *   node scripts/sync-favorite-films.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const CONFIG = {
  listId: '299607',
  mubiHeaders: { Client: 'web', 'Client-Country': 'US', Accept: 'application/json' },
  outFile: path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'data', 'favoriteFilms.ts'),
};

// MUBI doesn't flag series on list entries, so the ones that aren't episodes are listed here.
const SERIES_TITLES = new Set(['The Wire', 'The Sopranos', 'True Detective: Season One', 'Planet Earth II']);

async function fetchListFilms() {
  const all = [];
  for (let page = 1; ; page++) {
    const url = new URL(`https://api.mubi.com/v3/lists/${CONFIG.listId}/list_films`);
    url.searchParams.set('per_page', '50');
    url.searchParams.set('page', String(page));
    const res = await fetch(url, { headers: CONFIG.mubiHeaders, cache: 'no-store' });
    if (!res.ok) throw new Error(`MUBI HTTP ${res.status}`);
    const data = await res.json();
    all.push(...data.list_films);
    if (!data.meta?.next_page) break;
  }
  return all.sort((a, b) => a.position - b.position);
}

function convert(entry) {
  const film = entry.film;
  // A single episode stands in for the whole show (e.g. Twin Peaks → "Northwest Passage").
  const seriesTitle = film.episode?.series_title;
  const title = seriesTitle || film.title;
  return {
    rank: entry.position,
    title,
    directors: (film.directors || []).map((d) => d.name),
    countries: film.historic_countries || [],
    year: film.year,
    isSeries: Boolean(seriesTitle) || SERIES_TITLES.has(film.title),
    still: film.stills?.standard || film.still_url || '',
    url: film.web_url,
  };
}

const films = (await fetchListFilms()).map(convert);

const output = `/**
 * Single source of truth for the Favorites tab on /list-of-seen-films.
 *
 * Generated by scripts/sync-favorite-films.mjs from the MUBI "Favorite films"
 * list — re-run the script instead of editing by hand. Array order is the ranking.
 */

export interface FavoriteFilm {
  rank: number
  title: string
  directors: string[]
  countries: string[]
  year: number
  isSeries: boolean
  still: string
  url: string
}

export const favoriteFilms: FavoriteFilm[] = ${JSON.stringify(films, null, 2)}
`;

fs.writeFileSync(CONFIG.outFile, output);
console.log(`Wrote ${films.length} films to ${path.relative(process.cwd(), CONFIG.outFile)}`);
console.log(`Series: ${films.filter((f) => f.isSeries).map((f) => f.title).join(', ')}`);
